#!/usr/bin/env python3
"""Generate the SM8250 QMP gen3x1 PCIe PHY init tables for DaguPcieDxe.

Reads the tables straight from the Linux tree so the UEFI driver programs
exactly what drivers/phy/qualcomm/phy-qcom-qmp-pcie.c does for
"qcom,sm8250-qmp-gen3x1-pcie-phy" (sm8250_qmp_gen3x1_pciephy_cfg): the common
tables, then the RC tables. Register names are resolved from the qmp headers.

  tools/winarm/gen-qmp-pcie-tables.py > winarm/overlay/xiaomi-dagu/Driver/DaguPcieDxe/QmpPcieTables.inc
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
Q = os.path.join(ROOT, "linux-mainline/linux/drivers/phy/qualcomm")
SRC = open(os.path.join(Q, "phy-qcom-qmp-pcie.c")).read()

defs = {}
for h in os.listdir(Q):
    if h.endswith(".h"):
        for m in re.finditer(r"#define\s+(\w+)\s+(0x[0-9a-fA-F]+|\d+)\b", open(os.path.join(Q, h)).read()):
            defs.setdefault(m.group(1), int(m.group(2), 0))

# (table name, block) in programming order: qmp_pcie_init_registers() writes
# serdes, tx, rx, pcs, pcs_misc for tbls, then the same for tbls_rc.
ORDER = [
    ("sm8250_qmp_pcie_serdes_tbl", "SERDES"),
    ("sm8250_qmp_pcie_tx_tbl", "TX"),
    ("sm8250_qmp_pcie_rx_tbl", "RX"),
    ("sm8250_qmp_pcie_pcs_tbl", "PCS"),
    ("sm8250_qmp_pcie_pcs_misc_tbl", "PCS_MISC"),
    ("sm8250_qmp_gen3x1_pcie_serdes_tbl", "SERDES"),
    ("sm8250_qmp_gen3x1_pcie_rx_tbl", "RX"),
    ("sm8250_qmp_gen3x1_pcie_pcs_tbl", "PCS"),
    ("sm8250_qmp_gen3x1_pcie_pcs_misc_tbl", "PCS_MISC"),
]
# qmp_pcie_offsets_v4x1
BASE = {"SERDES": 0x000, "TX": 0x200, "RX": 0x400, "PCS": 0x800, "PCS_MISC": 0xC00}

out = ["// Generated by tools/winarm/gen-qmp-pcie-tables.py from",
       "// linux-mainline/linux/drivers/phy/qualcomm/phy-qcom-qmp-pcie.c",
       "// (sm8250_qmp_gen3x1_pciephy_cfg: common tables, then RC tables).",
       "// { offset from the PHY base 0x01c06000, value }. Do not edit."]
total = 0
for name, blk in ORDER:
    m = re.search(r"static const struct qmp_phy_init_tbl %s\[\] = \{(.*?)\n\};" % name, SRC, re.S)
    if not m:
        sys.exit("table not found: " + name)
    out.append("  // %s (%s +0x%03x)" % (name, blk, BASE[blk]))
    for reg, val in re.findall(r"QMP_PHY_INIT_CFG\((\w+),\s*(0x[0-9a-fA-F]+|\d+)\)", m.group(1)):
        if reg not in defs:
            sys.exit("unknown register " + reg)
        out.append("  { 0x%04x, 0x%02x }, // %s" % (BASE[blk] + defs[reg], int(val, 0), reg))
        total += 1
print("\n".join(out))
print("// %d writes" % total)
